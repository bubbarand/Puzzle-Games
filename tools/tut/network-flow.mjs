// Plays the network-flow tutorial with real mouse input. Usage: node tools/tut/network-flow.mjs [dark] [reduced] [outdir]
import { launch, sleep } from './lib.mjs';
import { bestFlow, makeLevel } from '../../product/logic/network-flow.js';
const [, , a1, a2, out = '/tmp'] = process.argv;
const t = await launch({ dark: a1 === 'dark', reduced: a2 === 'reduced' });
const fail = (m) => { console.log('FAIL', m, t.logs); process.exitCode = 1; };
await t.open('network-flow');
await t.waitTitle(/Fill the boxes/);
await t.shot(`${out}/nf-1.png`);
const valve = (e) => t.ev(`(()=>{const r=document.querySelector('[data-e="${e}"]').getBoundingClientRect();return {cx:r.left+r.width/2,cy:r.top+r.height/2,w:r.width}})()`);
const press = async (e) => { const c = await valve(e); await t.tap(c.cx, c.cy); await sleep(150); };
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Open a valve/);
const v0 = await valve(0); if (v0.w < 44) fail('valve under 44 px: ' + v0.w);
await press(0); await t.waitTitle(/Plus and minus/);
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Take it back/);
await t.tapSel('[data-a=undo]'); await t.waitTitle(/Your turn/);
await sleep(800); await t.shot(`${out}/nf-5.png`);
const flow = bestFlow(makeLevel(1));
for (let e = 0; e < flow.length; e++) for (let k = 0; k < flow[e]; k++) await press(e);
await t.waitTitle(/complete/, 6000);
await t.shot(`${out}/nf-done.png`);
if (await t.ev(`localStorage.getItem('puzzle-app-v1')`)) fail('progress changed');
await t.tapSel('.tut-btn.go'); await sleep(500);
if (await t.coach()) fail('coach still open');
if (await t.ev(`localStorage.getItem('puzzle-app-tutorial-v1')`) !== '{"network-flow":true}') fail('seen flag');
if (t.logs.length) fail('console errors');
console.log(process.exitCode ? 'RESULT FAIL' : 'RESULT PASS network-flow');
await t.close();
