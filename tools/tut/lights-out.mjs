// Plays the lights-out tutorial with real mouse input. Usage: node tools/tut/lights-out.mjs [dark] [reduced] [outdir]
import { launch, sleep } from './lib.mjs';
import { solutions, makeLevel } from '../../product/logic/lights-out.js';
const [, , a1, a2, out = '/tmp'] = process.argv;
const t = await launch({ dark: a1 === 'dark', reduced: a2 === 'reduced' });
const fail = (m) => { console.log('FAIL', m, t.logs); process.exitCode = 1; };
await t.open('lights-out');
await t.waitTitle(/Lights off/);
await t.shot(`${out}/lo-1.png`);
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Tap a bulb/);
const cell = (i) => t.ev(`(()=>{const r=document.querySelectorAll('.lo-cell')[${i}].getBoundingClientRect();return {cx:r.left+r.width/2,cy:r.top+r.height/2}})()`);
const press = async (i) => { const c = await cell(i); await t.tap(c.cx, c.cy); await sleep(150); };
await press(12); await t.waitTitle(/Neighbors flip/);
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Take it back/);
await t.tapSel('[data-a=undo]'); await t.waitTitle(/Your turn/);
await sleep(800); await t.shot(`${out}/lo-5.png`);
for (const i of solutions(makeLevel(1).grid)[0]) await press(i);
await t.waitTitle(/complete/, 6000);
await t.shot(`${out}/lo-done.png`);
if (await t.ev(`localStorage.getItem('puzzle-app-v1')`)) fail('progress changed');
await t.tapSel('.tut-btn.go'); await sleep(500);
if (await t.coach()) fail('coach still open');
if (await t.ev(`localStorage.getItem('puzzle-app-tutorial-v1')`) !== '{"lights-out":true}') fail('seen flag');
if (t.logs.length) fail('console errors');
console.log(process.exitCode ? 'RESULT FAIL' : 'RESULT PASS lights-out');
await t.close();
