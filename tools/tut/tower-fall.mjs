// Plays the tower-fall tutorial with real mouse input. Usage: node tools/tut/tower-fall.mjs [dark] [reduced] [outdir]
import { launch, sleep } from './lib.mjs';
import * as logic from '../../product/logic/tower-fall.js';
import { bfs } from '../../product/logic/solve.js';
const [, , a1, a2, out = '/tmp'] = process.argv;
const t = await launch({ dark: a1 === 'dark', reduced: a2 === 'reduced' });
const fail = (m) => { console.log('FAIL', m, t.logs); process.exitCode = 1; };
await t.open('tower-fall');
await t.waitTitle(/Stop the jellies/);
await t.shot(`${out}/tf-1.png`);
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Place a tower/);
const slot = (p) => t.rect(`.tf-sl[data-p="${p}"] .tf-hit`);
const tapSlot = async (p) => { const r = await slot(p); await t.tap(r.cx, r.cy); await sleep(150); };
const level = logic.makeLevel(1);
const sol = bfs(logic, level).path;
const places = sol.filter((m) => m.t === 'place').map((m) => m.p);
await tapSlot(level.slots[0]); await t.waitTitle(/Tower range/);
await t.shot(`${out}/tf-3.png`);
await t.tapSel('.tut-btn.go'); await t.waitTitle(/Take it back/);
await t.tapSel('[data-a=undo]'); await t.waitTitle(/Your turn/);
await sleep(800); await t.shot(`${out}/tf-5.png`);
for (const p of places) await tapSlot(p);
await t.tapSel('.tf-go');
await t.waitTitle(/complete/, 15000);
await t.shot(`${out}/tf-done.png`);
if (await t.ev(`localStorage.getItem('puzzle-app-v1')`)) fail('progress changed');
await t.tapSel('.tut-btn.go'); await sleep(500);
if (await t.coach()) fail('coach still open');
if (await t.ev(`localStorage.getItem('puzzle-app-tutorial-v1')`) !== '{"tower-fall":true}') fail('seen flag');
if (t.logs.length) fail('console errors');
console.log(process.exitCode ? 'RESULT FAIL' : 'RESULT PASS tower-fall');
await t.close();
